"""Traces the logo PNG's alpha mask into vector polygons and writes them as
Swift source, so the app can draw the logo crisply at any size.
Usage: python3 tools/trace_logo.py Resources/brand/logo-source.png Sources/Overhead/LogoPath.swift"""
import sys
import numpy as np
from PIL import Image

src, out = sys.argv[1], sys.argv[2]
alpha = np.array(Image.open(src).convert("RGBA"))[:, :, 3]
mask = alpha > 127
H, W = mask.shape

# Label connected components (4-connectivity) with an iterative flood fill.
labels = np.zeros(mask.shape, dtype=np.int32)
count = 0
for y, x in zip(*np.nonzero(mask)):
    if labels[y, x]:
        continue
    count += 1
    stack = [(y, x)]
    labels[y, x] = count
    while stack:
        cy, cx = stack.pop()
        for ny, nx in ((cy + 1, cx), (cy - 1, cx), (cy, cx + 1), (cy, cx - 1)):
            if 0 <= ny < H and 0 <= nx < W and mask[ny, nx] and not labels[ny, nx]:
                labels[ny, nx] = count
                stack.append((ny, nx))

def trace(comp):
    """Walk the pixel-edge boundary of a component (cracks between pixels)."""
    m = np.pad(labels == comp, 1)
    # Directed boundary edges with the shape kept on the left (clockwise in image coords).
    edges = {}
    ys, xs = np.nonzero(m)
    for y, x in zip(ys, xs):
        if not m[y - 1, x]: edges[(x, y)] = (x + 1, y)
        if not m[y, x + 1]: edges[(x + 1, y)] = (x + 1, y + 1)
        if not m[y + 1, x]: edges[(x + 1, y + 1)] = (x, y + 1)
        if not m[y, x - 1]: edges[(x, y + 1)] = (x, y)
    start = min(edges)  # outer boundary starts at the top-left-most corner
    pts, p = [start], edges[start]
    while p != start:
        pts.append(p)
        p = edges[p]
    return [(px - 1, py - 1) for px, py in pts]

def smooth(pts, k=3):
    n = len(pts)
    a = np.array(pts, dtype=float)
    out = np.zeros_like(a)
    for i in range(-k, k + 1):
        out += np.roll(a, i, axis=0)
    return out / (2 * k + 1)

def rdp(points, eps):
    if len(points) < 3:
        return points
    a, b = points[0], points[-1]
    ab = b - a
    norm = np.hypot(*ab) or 1.0
    d = np.abs((ab[0] * (points[:, 1] - a[1]) - ab[1] * (points[:, 0] - a[0]))) / norm
    i = int(np.argmax(d))
    if d[i] > eps:
        return np.vstack([rdp(points[: i + 1], eps)[:-1], rdp(points[i:], eps)])
    return np.vstack([a, b])

shapes = []
for comp in range(1, count + 1):
    if (labels == comp).sum() < 500:  # ignore specks
        continue
    pts = smooth(trace(comp))
    half = len(pts) // 2
    simplified = np.vstack([rdp(pts[: half + 1], 0.8)[:-1], rdp(np.vstack([pts[half:], pts[:1]]), 0.8)[:-1]])
    shapes.append(simplified)

allpts = np.vstack(shapes)
minx, miny = allpts.min(axis=0)
maxx, maxy = allpts.max(axis=0)
side = max(maxx - minx, maxy - miny)
ox = minx - (side - (maxx - minx)) / 2
oy = miny - (side - (maxy - miny)) / 2

lines = ["// Generated by tools/trace_logo.py from Resources/brand/logo-source.png. Do not edit by hand.",
         "import CoreGraphics", "",
         "enum LogoPath {",
         "    /// Polygons in a 0...1 square, y pointing down.",
         "    static let polygons: [[CGPoint]] = ["]
for s in shapes:
    body = ", ".join(f"CGPoint(x: {(x - ox) / side:.5f}, y: {(y - oy) / side:.5f})" for x, y in s)
    lines.append(f"        [{body}],")
lines += ["    ]", "}", ""]
open(out, "w").write("\n".join(lines))
print(f"{len(shapes)} shapes, points per shape: {[len(s) for s in shapes]}")
